"""Simulation of the design trap (plan D14 item 2): accidents that generate their own event reports pull the
within-plant-year estimate below the truth, and removing reports from the accident day and the 2 days after brings
it back.

Real event counts and the primary panel's plant-years and accident counts; no real accident dates. Each draw places
each plant-year's accidents on random at-risk days of that plant-year:
  (a) no effect: uniformly;
  (b) planted 1.3 per doubling: with probability proportional to (1 + events in the 90-day window) ** log2(1.3).
Each simulated accident adds reports at its plant at the observed excess, computed from
data/manifests/stored_checks.json: Poisson((212 - 9.7) / 541 = 0.374) on the accident day and Poisson(0.006) on each
of the 2 days after (26 reports on those days against 19.4 expected). (A first run used 0.03 for the 2 days after,
which overstated the excess; plan D16 item 2.) Fits: naive (90 and 365-day windows) and
with the reports of the accident day and the 2 days after removed. 20 draws per scenario.
Output: data/manifests/sim_design_trap.json
"""
import json
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import phase5_diag_own_reports as OR  # noqa: E402
import phase5_h1 as P  # noqa: E402

OUT = P.h1.ROOT / "data" / "manifests" / "sim_design_trap.json"
_S0 = json.loads((P.h1.ROOT / "data/manifests/stored_checks.json").read_text())["accident_day_reports"]
_D0 = (_S0["events_on_day_0"] - _S0["expected_per_day_from_plant_average"]) / _S0["accident_days"]
_D12 = (_S0["events_days_0_to_2"] - _S0["events_on_day_0"] - 2 * _S0["expected_per_day_from_plant_average"]) / (
    2 * _S0["accident_days"])
EXCESS = {0: _D0, 1: _D12, 2: _D12}
DRAWS = 20


_S = {}


def setup():
    if "v" in _S:
        return _S["v"]
    plants, ev, acc, *_ = P.tables("v2")
    cnt = P.event_counts(ev)
    pan = P.h1_run(keep_panel=True)["panel"][["plant_id", "day", "plant_year", "y", "E_x"]]
    _S["v"] = (cnt, pan)
    return _S["v"]


def one(args):
    scenario, seed = args
    cnt, pan = setup()
    rng = np.random.default_rng(seed)
    b = np.log2(1.3) if scenario == "b" else 0.0
    rows = []
    for py, g in pan.groupby("plant_year"):
        k = int(g.y.sum())
        w = (1 + g.E_x.values) ** b
        pick = rng.choice(len(g), size=k, replace=True, p=w / w.sum())
        rows += [(g.plant_id.iloc[0], g.day.iloc[i]) for i in pick]
    fa = pd.DataFrame(rows, columns=["plant_id", "date"])
    # reports generated by the simulated accidents
    add = []
    for p, d in zip(fa.plant_id, fa.date):
        for j, lam in EXCESS.items():
            n = rng.poisson(lam)
            if n:
                add.append((p, d + pd.Timedelta(days=j), n))
    a = pd.DataFrame(add, columns=["plant_id", "day", "n"]).groupby(["plant_id", "day"]).n.sum()
    inj = cnt.add(a, fill_value=0)
    inj.index = inj.index.set_names(["plant_id", "day"])
    fixed, _ = OR.remove_after(inj, fa.rename(columns={"date": "day"}), 2)
    out = {"scenario": scenario, "seed": seed}
    for w in (90, 365):
        r = P.h1_run(window=w, accidents=fa, exposures={"x": inj}, statewide_counts=inj)
        out[f"naive_{w}"] = r["terms"]["x"]["rr_doubling"]
        r = P.h1_run(window=w, accidents=fa, exposures={"x": fixed}, statewide_counts=inj)
        out[f"fixed_{w}"] = r["terms"]["x"]["rr_doubling"]
    print(out, flush=True)
    return out


def main():
    jobs = [(s, 1000 * (s == "b") + i) for s in ("a", "b") for i in range(DRAWS)]
    with Pool(3) as pool:
        res = pool.map(one, jobs, chunksize=1)
    d = pd.DataFrame(res)
    summ = {}
    for s, g in d.groupby("scenario"):
        summ[{"a": "no_effect", "b": "planted_1.3"}[s]] = {
            c: {"median": round(float(g[c].median()), 3), "p10_p90": [round(float(g[c].quantile(q)), 3) for q in (0.1, 0.9)]}
            for c in ("naive_90", "fixed_90", "naive_365", "fixed_365")}
    OUT.write_text(json.dumps({"note": __doc__.split("Output:")[0].strip(), "draws_per_scenario": DRAWS,
                               "summary": summ, "draws": res}, indent=1, default=float) + "\n")
    print(json.dumps(summ, indent=1))


if __name__ == "__main__":
    main()
